#!/usr/bin/env python3
"""Bake the Force's large Q-link value font (as drawn while a knob is turned) into flfont_big.h, harvested from a
usbmon capture of the real Force (local/captures/qlinks.bin, `forcelink cap`). The glyph pixels come from the user's
own capture at build time; this file holds only fingerprints (sha1 of each glyph's rows) and the character each one
is. The header is generated, never committed. usage: gen_big_font.py <capture.bin> [out.h]"""
import hashlib
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'tools'))
import force_capture_render as r  # noqa: E402

FINGERPRINT = {  # sha1(rows joined by '/')[:10] -> character (labelled 2026-10-25 from the capture)
    '793e0e9a39': '.', 'ecd5eb3fea': 'I', 'b64a19128f': '1', '19fbb8c7d2': '-', '463abf7dd9': '0',
    'd366629088': 'd', '4ade767f8a': '+', '1cd9769c9e': '9', '0ce158aa32': '5', '971e0b2e57': '7',
    '47c3ae6861': '3', '4f94d4fdd8': '2', '43853dd3bc': '6', 'ecb2160c39': '4', 'cef24014d6': '8',
    'c067d82b20': 'F', '91735dd76b': 'L', 'ab0ba3b4c7': 'B', '957345bc41': 'N', 'e47d12dca1': 'C',
    'e1469f3463': 'R',
}
Y0, H = 5, 12  # ink rows 5-16


def glyphs(path):
    img, found = {}, {}
    for _, _, m in r.midi_out(path):
        if m[:5] != b'\xf0\x47\x7f\x40\x0b':
            continue
        d = r.oled_blit(img, m)
        if d >= 8:
            continue
        f = img[d]
        tall = [y for y in range(3, 18) if any(f[y])]
        if not tall or tall[-1] - tall[0] < 9:
            continue
        cols = [x for x in range(128) if any(f[y][x] for y in range(Y0, Y0 + H))]
        seg = []
        for x in range(129):
            if x < 128 and x in cols:
                seg.append(x)
                continue
            if seg:
                rows = [''.join('#' if f[y][c] else '.' for c in seg) for y in range(Y0, Y0 + H)]
                ch = FINGERPRINT.get(hashlib.sha1('/'.join(rows).encode()).hexdigest()[:10])
                if ch:
                    found.setdefault(ch, rows)
                seg = []
    return found


def main():
    src = sys.argv[1]
    out = sys.argv[2] if len(sys.argv) > 2 else 'flfont_big.h'
    if not os.path.exists(src):                       # no capture: every character from the scaled small font
        print(f'warning: {src} not found; the large Q-link font falls back to the scaled small font')
        found = {}
        write(out, found)
        return
    found = glyphs(src)
    missing = sorted(set(FINGERPRINT.values()) - set(found))
    if missing:
        sys.exit(f'{src}: no glyph for {"".join(missing)}; record a Q-link capture (forcelink cap) with those values')
    write(out, found)
    print(f'ok: {len(found)} glyphs from {src} -> {out}')


def write(out, found):
    lines = ['/* GENERATED by gen_big_font.py from a local capture of the real Force -- do not edit, do not commit. */',
             '#define FBIG_H 12',
             '/* per character 32..126: width (0 = not harvested: drawn from the small font, scaled), then 12 rows, */',
             '/* bit 15 = leftmost pixel */',
             'static const unsigned short fbig[95][13] = {']
    for c in range(32, 127):
        rows = found.get(chr(c))
        if not rows:
            lines.append('  {0},')
            continue
        bits = [sum(1 << (15 - i) for i, v in enumerate(row) if v == '#') for row in rows]
        lines.append('  {%d,%s},' % (len(rows[0]), ','.join(str(b) for b in bits)))
    lines.append('};')
    open(out, 'w').write('\n'.join(lines) + '\n')


if __name__ == '__main__':
    main()

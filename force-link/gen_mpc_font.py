#!/usr/bin/env python3
"""Bake MPC's own Q-link OLED font (5x7 proportional, 8 bytes per glyph, row-major, MSB = left) into
flfont_mpc.h, read from the user's MPC binary at build time. The header is generated, never committed.
usage: gen_mpc_font.py <MPC binary> [out.h]
The table is found by content ('D' and 'R' glyphs as captured from a real Force), not by offset."""
import sys

D = bytes.fromhex('00f08888888888f0')
R = bytes.fromhex('00f08888f0a09088')
d = open(sys.argv[1], 'rb').read()
out = sys.argv[2] if len(sys.argv) > 2 else 'flfont_mpc.h'
base = None
i = d.find(D)
while i >= 0:
    b = i - ord('D') * 8
    if d[b + ord('R') * 8:b + ord('R') * 8 + 8] == R and d[b + 32 * 8:b + 33 * 8] == bytes(8):
        base = b; break
    i = d.find(D, i + 1)
if base is None: sys.exit('MPC OLED font not found in ' + sys.argv[1])


def width(g):
    m = 0
    for x in g: m |= x
    return 0 if not m else 8 - ((m & -m).bit_length() - 1)


lines = ['/* GENERATED by gen_mpc_font.py from the local MPC binary -- do not edit, do not commit. */',
         '#define FMPC_H 8', 'static const unsigned char fmpc[95][9] = {   /* 8 rows (row 0 blank), then glyph width */']
for c in range(32, 127):
    g = d[base + c * 8:base + c * 8 + 8]
    w = 4 if c == 32 else width(g)            # space advances 4 + 1, as on the Force (captured)
    lines.append('  {' + ','.join(str(x) for x in g) + ',%d},' % w)
lines.append('};')
open(out, 'w').write('\n'.join(lines) + '\n')
print('ok: table at', hex(base), '->', out)

#!/usr/bin/env python3
"""Bake ASCII 32..126 of two Linux console PSF fonts into flfont.h (1 byte/row, MSB = leftmost pixel)."""
import gzip,struct,sys
def load(path):
    d=gzip.open(path).read()
    if d[:4]==b'\x72\xb5\x4a\x86':   # psf2
        _,ver,hs,flags,n,cs,h,w=struct.unpack('<8I',d[:32]); return d[hs:],cs,h,w,n
    if d[:2]==b'\x36\x04':           # psf1: 8 px wide, charsize = height
        cs=d[3]; return d[4:],cs,cs,8,256
    raise SystemExit('unknown psf')
out=['/* GENERATED by gen_font.py from Linux console fonts (Terminus, SIL OFL) -- do not edit. */']
for name,path in (('f6x12','/usr/share/consolefonts/CyrAsia-Terminus12x6.psf.gz'),('f8x16','/usr/share/consolefonts/CyrAsia-TerminusBold16.psf.gz')):
    g,cs,h,w,n=load(path); assert w<=8
    out.append(f'#define {name.upper()}_H {h}\n#define {name.upper()}_W {w}\nstatic const unsigned char {name}[95][{h}] = {{')
    for c in range(32,127):
        out.append('  {'+','.join(str(g[c*cs+r]) for r in range(h))+'},')
    out.append('};')
open('flfont.h','w').write('\n'.join(out)+'\n')
print('ok')

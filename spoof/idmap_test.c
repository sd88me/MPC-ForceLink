/* offline test of idmap(): gcc -o t idmap_test.c && ./t */
#include <stdio.h>
#include <string.h>
#include <stddef.h>
typedef struct { int pos; int kind; } idmap_t;
void idmap(idmap_t *st, unsigned char *b, size_t n, unsigned char from, unsigned char to);
#define IDMAP_ONLY
static int check(const char *name, unsigned char *in, size_t n, const unsigned char *want, size_t split, unsigned char f, unsigned char t)
{
	idmap_t st = {-1, 0};
	idmap(&st, in, split, f, t);
	idmap(&st, in + split, n - split, f, t);
	int ok = !memcmp(in, want, n);
	printf("%-28s %s\n", name, ok ? "ok" : "FAIL");
	return ok;
}
int main(void)
{
	int ok = 1;
	for (size_t sp = 0; sp <= 6; sp++) {
		unsigned char a[] = {0xF0,0x47,0x7F,0x04,0x65,0x00,0x04,0x01,0x7F,0x00,0x00,0xF7};
		const unsigned char w[] = {0xF0,0x47,0x7F,0x40,0x65,0x00,0x04,0x01,0x7F,0x00,0x00,0xF7};
		ok &= check("akai header MPC->ctl", a, sizeof a, w, sp, 0x04, 0x40);
	}
	unsigned char c[] = {0xF0,0x47,0x00,0x04,0x52,0x00,0x04,0x13,0x75,0x21,0x69,0xF7};
	const unsigned char cw[] = {0xF0,0x47,0x00,0x40,0x52,0x00,0x04,0x13,0x75,0x21,0x69,0xF7};
	ok &= check("challenge 47 00 id", c, sizeof c, cw, 5, 0x04, 0x40);
	unsigned char r[] = {0xF0,0x7E,0x00,0x06,0x02,0x47,0x40,0x00,0x19,0x00,0xF7, 0x99,0x40,0x7F, 0xF0,0x47,0x7F,0x40,0x53,0xF7};
	const unsigned char rw[] = {0xF0,0x7E,0x00,0x06,0x02,0x47,0x04,0x00,0x19,0x00,0xF7, 0x99,0x40,0x7F, 0xF0,0x47,0x7F,0x04,0x53,0xF7};
	for (size_t sp = 0; sp < sizeof r; sp += 3)
		{ unsigned char x[sizeof r]; memcpy(x, r, sizeof r); ok &= check("identity+note+akai ctl->MPC", x, sizeof x, rw, sp, 0x40, 0x04); }
	unsigned char d[] = {0xF0,0x47,0x7F,0x40,0x0B,0x04,0x40,0x40,0xF7};   /* 0x40 in payload must stay */
	const unsigned char dw[] = {0xF0,0x47,0x7F,0x04,0x0B,0x04,0x40,0x40,0xF7};
	ok &= check("payload 0x40 untouched", d, sizeof d, dw, 0, 0x40, 0x04);
	puts(ok ? "ALL OK" : "FAILURES");
	return !ok;
}
